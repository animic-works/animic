/**
 * 登録する内容。IDは環境によらず同じにし、書き出したファイルを別の環境で読み込んだときに同じ表現として扱う。
 * グループのIDはジャンルのキー、表現のIDはキーとタグから作る。
 */
export const initialPromptGroups: PromptGroup[] = groups.map((group, groupIndex) => ({
  id: group.key,
  label: group.label,
  tone: group.tone,
  target: group.target,
  sortOrder: groupIndex,
  phrases: group.entries.map(([label, tag, aliases = []], index) => ({
    id: `${group.key}-${tag.replaceAll(/[^A-Za-z0-9]+/g, "-")}`,
    label,
    suffix: "",
    tag,
    note: "",
    aliases,
    imageId: null,
    sortOrder: index,
  })),
}));
